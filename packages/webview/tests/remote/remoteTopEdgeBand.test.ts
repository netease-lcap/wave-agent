import fs from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * The top-edge band the remote page paints in the installed (home-screen) shape.
 *
 * iOS 27 draws a system blur over the top of an installed web app — the status
 * bar plus ~40pt below it — which smears the page's own header, and nothing on
 * the page can turn it off (`backdrop-filter: none`, `theme-color` and
 * `apple-mobile-web-app-status-bar-style` are all measured as no-ops; the last
 * one is deprecated, and *removing* it only hands the status bar a system-chosen
 * flat colour, and can zero out `env(safe-area-inset-top)` and letterbox the
 * page — WebKit bugs 324438 / 329103 / 330085 / 325807). The one thing that
 * suppresses it is the page painting an opaque element on its very top edge: the
 * system then uses that as the status-bar colour instead of blurring.
 *
 * ⚠️ What this file can and cannot see. The blur itself needs a real iPhone
 * running iOS 27 — it is drawn by the system, over the page, in a browser mode no
 * headless test can enter (that is also why the rule is read as text here and
 * re-injected by `e2e/remote-page-viewport.e2e.ts` rather than matched as a
 * media query at runtime). What is pinned here is the wiring that band depends on
 * and that fails **silently** when any half of it drifts: the element exists in
 * the shipped page (it is generated by `remote/build.mjs`, so nothing in the
 * webview bundle carries it), exactly one rule paints it and that rule only
 * applies in the installed shape, and the declarations that actually buy the
 * suppression — an opaque, full-width, edge-hugging fixed box that takes no clicks
 * — are intact. A band that stops painting just leaves the page blurred again;
 * there is no error to notice.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const WEBVIEW = resolve(HERE, "../..");
const read = (rel: string) => fs.readFileSync(resolve(WEBVIEW, rel), "utf-8");
const strip = (css: string) => css.replace(/\/\*[\s\S]*?\*\//g, "");

const build = read("remote/build.mjs");
const pageHtml = build.match(/<body>([\s\S]*?)<\/body>/)?.[1] ?? "";
const globals = strip(read("src/styles/globals.css"));

/** The body of one at-rule block, brace-matched (`@media … { … }`). */
const atRule = (css: string, prelude: string) => {
  const start = css.indexOf(`${prelude} {`);
  if (start < 0) return "";
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === "{") depth += 1;
    if (css[i] === "}") depth -= 1;
    if (depth === 0) return css.slice(open + 1, i);
  }
  return "";
};

const standalone = atRule(globals, "@media (display-mode: standalone)");
/** The one rule that paints the band (`#remote-top-edge { … }`, brace-matched). */
const bandStart = standalone.indexOf("#remote-top-edge {");
const band = standalone.slice(
  bandStart,
  bandStart + standalone.slice(bandStart).indexOf("}") + 1,
);

describe("remote page — the top-edge band that suppresses the iOS 27 blur", () => {
  it("ships the element in the generated page, above the app root", () => {
    // The band is a real element, not a `body::before`: every case where iOS
    // stopped blurring involved an actual edge-hugging fixed container, and a
    // pseudo-element has no such evidence. It is also the first child so the
    // page has it at first paint, before anything can fail to run.
    expect(pageHtml).toContain(
      '<div id="remote-top-edge" aria-hidden="true"></div>',
    );
    expect(pageHtml.indexOf('id="remote-top-edge"')).toBeGreaterThan(-1);
    expect(pageHtml.indexOf('id="remote-top-edge"')).toBeLessThan(
      pageHtml.indexOf('id="root"'),
    );
  });

  it("paints it only in the installed shape", () => {
    // A Safari tab only gets the thin blur behind the status bar, and the other
    // four hosts do not carry the element at all — an unconditional rule would
    // put a 12px band over the top of the header there. Hence the guard: every
    // mention of the element (the paint rule plus the two tone rules that give
    // the status banner a matching status-bar colour) lives inside it.
    expect(band).not.toBe("");
    expect(
      globals.replace(standalone, "").match(/#remote-top-edge/g),
    ).toBeNull();
  });

  it("paints an opaque, full-width, edge-hugging box that takes no clicks", () => {
    expect(band).toContain("display: block");
    // `position: fixed` at the top edge is the form the workaround was measured
    // in; anything that scrolls with the content leaves the edge uncovered.
    expect(band).toContain("position: fixed");
    expect(band).toContain("inset: 0 0 auto 0");
    // Opaque, and the same colour the header/body paint — otherwise the band is
    // its own visible seam. The token follows both themes by itself.
    expect(band).toContain("background: var(--vscode-panel-background)");
    // The floor is what the suppression was measured at (≥6px high, ≥80% wide,
    // within 4px of the top; one device needed ~12px). The inset is the status
    // bar's own height, so on a normal device the band covers exactly the status
    // bar; the floor is the fallback for the builds where that env() is 0.
    // The number lives on the page, not on the band: the body's padding-top and
    // the status banner's own compensation read the same variable (below), and
    // three copies of `max(12px, env(…))` is how they drift apart.
    expect(band).toContain("height: var(--remote-top-edge-h)");
    // The header's buttons sit under the band's bottom edge on short insets —
    // without this the top rows of those 40px targets are dead.
    expect(band).toContain("pointer-events: none");
    // Background layer, not a foreground one: dialogs / menus / tooltips
    // (1000+) still paint over it, and their own opaque top edge is what the
    // system samples then.
    expect(band).toMatch(/z-index: 1\b/);
  });

  it("色带自己不进布局，让位交给 body —— 三个落点读同一个变量", () => {
    // 色带必须是那个「贴边 fixed」的形态（上面一条已经钉了），所以它自己不能变成
    // 流内元素、也不能靠自己的 padding 让位。
    expect(band).not.toContain("padding");
    expect(band).not.toContain("margin");
    expect(band).not.toContain("position: relative");
    expect(band).not.toContain("position: sticky");
    // 覆盖层不会把流内内容挤开，于是让位只能写在 body 上。三者（页面变量、body 的
    // 让位、色带高度）**必须读同一个变量**：各写一份 `max(12px, env(…))`，任何一处被
    // 单独改动都会立刻错开，色带重新压住页面最顶上那块内容。实测代价（2026-11-13）：
    // 安全区归零的机型上，顶栏 40px 按钮的高亮底色顶边被切掉 4px；状态横幅的文案
    // 距红条顶 6px、距底 18px（后来横幅改成贴屏幕最顶，见下一条）。
    expect(standalone).toContain(
      "--remote-top-edge-h: max(12px, env(safe-area-inset-top, 0px))",
    );
    const value = (css: string, prop: string) =>
      new RegExp(`${prop}:\\s*([^;]+);`).exec(css)?.[1].trim();
    expect(value(standalone, "padding-top")).toBe("var(--remote-top-edge-h)");
    expect(value(standalone, "height")).toBe("var(--remote-top-edge-h)");
  });

  it("状态横幅在顶边时，色带跟着它的 tone 走颜色", () => {
    // 色带唯一的职责是「在最顶边画一块不透明」，颜色由系统采样成状态栏底色，所以
    // 不该固定成页面底色。那条红色状态横幅用负 margin 贴到屏幕最顶（shim 的
    // `bannerStyle`），色带若还是页面底色，就在它上沿压出一条 12px 的深色缝——
    // 2026-11-13 用户：「红色横幅上面还有一点点黑条」。`:has()` 让横幅消失时自动
    // 失效，shim 不需要还原任何状态。
    expect(standalone).toMatch(
      /body:has\(> #remote-status\[data-tone="error"\]\)[\s\S]{0,40}#remote-top-edge \{\s*background: #5a1d1d;/,
    );
    expect(standalone).toMatch(
      /body:has\(> #remote-status\[data-tone="progress"\]\)[\s\S]{0,40}#remote-top-edge \{\s*background: #333333;/,
    );
  });

  it("keeps black-translucent even though Apple calls it deprecated", () => {
    // The tempting "fix" is to delete the deprecated key (a WebKit engineer asks
    // for exactly that): it does NOT remove the blur, and it can make
    // `env(safe-area-inset-top)` resolve to 0 and letterbox the page. The band
    // above is the fix; the key stays.
    expect(build).toContain(
      '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />',
    );
  });
});
