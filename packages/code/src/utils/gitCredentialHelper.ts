/**
 * Git credential helper installed for repositories cloned from a `wave://clone`
 * deep link (spec: docs/specs/desktop/desktop-deep-link.md「克隆出的仓库长期
 * 自动认证」).
 *
 * What lands in the repository config is *this command*, never the credential:
 *
 *     [credential]
 *         helper =
 *         helper = !exec '/Users/me/.wave/git-credential-wave'
 *
 * The empty first entry resets the helper list inherited from system/global
 * config. Without it a machine-wide store/cache helper (osxkeychain, manager,
 * credential-store) also runs and pins the first credential it sees, so later
 * logins and token refreshes would never be picked up.
 *
 * The helper is a plain `/bin/sh` script rather than a call back into the CLI:
 * git invokes it before *every* authenticated network operation, and booting
 * the Electron-bundled Node runtime for that would add seconds to each push. It
 * only needs the token sitting in `~/.wave/auth.json`, which the CLI keeps
 * current (including background refreshes).
 */

import { chmodSync, mkdirSync, writeFileSync } from "fs";
import * as path from "path";
import { AuthService } from "wave-agent-sdk";

/** Extensionless on purpose: git execs it through the shebang, and MSYS sh
 *  resolves a bare path that starts with `#!`. */
export const GIT_CREDENTIAL_HELPER_FILENAME = "git-credential-wave";

export interface InstalledGitCredentialHelper {
  /** Absolute path of the generated script. */
  path: string;
  /** Ready-to-use `credential.helper` value (written into repo config). */
  command: string;
}

/** `<home>/.wave/git-credential-wave` — next to `auth.json`. */
export function gitCredentialHelperPath(): string {
  return path.join(
    path.dirname(AuthService.getInstance().getAuthPath()),
    GIT_CREDENTIAL_HELPER_FILENAME,
  );
}

/**
 * (Re)write the helper script and return the config value that installs it.
 * Idempotent — safe to call on every deep-link clone.
 */
export function installGitCredentialHelper(): InstalledGitCredentialHelper {
  const scriptPath = gitCredentialHelperPath();
  mkdirSync(path.dirname(scriptPath), { recursive: true });
  writeFileSync(
    scriptPath,
    renderGitCredentialHelper(AuthService.getInstance().getAuthPath()),
    "utf-8",
  );
  chmodSync(scriptPath, 0o755);
  return { path: scriptPath, command: `!exec ${shellQuote(scriptPath)}` };
}

/** The script body. Exported for tests. */
export function renderGitCredentialHelper(authFilePath: string): string {
  return `#!/bin/sh
# Wave git credential helper — generated by CodeWave IDE.
# Rewritten on every deep-link clone; do not edit by hand.
#
# Prints the current Wave SSO token, read fresh from the login store on each
# request, so logging in (or the CLI refreshing the token) takes effect without
# touching any repository.

AUTH_FILE=${shellQuote(authFilePath)}

# Drain git's request: we only look at the capabilities it advertises below, and
# a helper that exits before reading stdin can get EPIPE'd.
input=$(cat 2>/dev/null) || input=

token=$(sed -n 's/.*"SSO_TOKEN"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' "$AUTH_FILE" 2>/dev/null | head -n 1)

if [ -z "$token" ]; then
	# Not logged in on this machine. Stop git right here: quit=true skips the
	# remaining helpers *and* the interactive prompt (there is no terminal when
	# the agent runs git), so the operation fails fast instead of hanging.
	echo "quit=true"
	exit 0
fi

case "$input" in
*capability\\[\\]=authtype*)
	echo "capability[]=authtype"
	echo "authtype=bearer"
	printf 'credential=%s\\n' "$token"
	;;
*)
	echo "username=oauth2"
	printf 'password=%s\\n' "$token"
	;;
esac
`;
}

/** Single-quote a value for `sh`, escaping embedded single quotes. */
export function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}
