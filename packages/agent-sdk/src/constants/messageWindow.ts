/**
 * 一次取数的字节上限。
 *
 * 条数挡不住图片：一条消息里的 base64 可以顶到 `OUTBOUND_IMAGE_MAX_BASE64_BYTES`
 * （5 MiB），一百条纯文字和一条截图在内存上差三个数量级。所以带 `limit` 的取数
 * **条数与字节同时收**，谁先到停谁。
 *
 * 至少保留 1 条：单条就超预算时也得返回它，否则调用方永远拿不到东西。
 *
 * 带 `limit` 的取数都受它约束：首屏、上翻取更早、远控页的尾段。不带参数的取数
 * （内部调用）不受限，它要的是整份。
 */
export const MESSAGE_SLICE_MAX_BYTES = 4 * 1024 * 1024;

/**
 * 一页的条数：首屏、上翻取更早、不带 `limit` 时的默认页大小都用它。
 *
 * `200` 与参考物同值（它取最新窗口与更早一页都是 `limit: 200`，条数交给渲染侧
 * 虚拟化扛）。首屏那一页的条数上限通常打不满——常驻列表以压缩为界，多数会话的
 * 长度落在「最近一次压缩 + 其后消息」这一段里；真正卡住绑定那一刻开销的是上面
 * 那道字节预算，图片是 base64 形态，200 条纯文字与 200 条带截图差三个数量级。
 */
export const MESSAGE_PAGE_SIZE = 200;
