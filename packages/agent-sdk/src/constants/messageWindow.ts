/**
 * 一次取数的字节上限。
 *
 * 条数挡不住图片：一条消息里的 base64 可以顶到 `OUTBOUND_IMAGE_MAX_BASE64_BYTES`
 * （5 MiB），一百条纯文字和一条截图在内存上差三个数量级。所以带 `limit` 的取数
 * **条数与字节同时收**，谁先到停谁。
 *
 * 至少保留 1 条：单条就超预算时也得返回它，否则调用方永远拿不到东西。
 *
 * 带 `limit` 的取数都受它约束：首屏、上翻取更早、远控页的尾段。不带参数的取数
 * （内部调用）不受限，它要的是整份。
 */
export const MESSAGE_SLICE_MAX_BYTES = 4 * 1024 * 1024;

/**
 * 首屏那一页的条数。一屏到两屏的量级：够填满窗口，又不至于让绑定会话那一刻
 * 构造出一大堆对象（那条用了 6 周的会话就是这样打开即黑屏的）。
 *
 * 没填满视口时页面侧会追着要下一页（有次数上限），所以这里宁可小一点。
 */
export const MESSAGE_FIRST_PAGE_SIZE = 20;

/**
 * 上翻一页的条数，也是不带 `limit` 时的默认页大小。
 *
 * 比首屏大一个量级：每翻一页都要从文件末尾往回扫到锚点，页越大越能摊薄这次
 * 扫描；而用户上翻本来就是「一次翻一段」的动作，不像首屏那样卡在打开的那一刻。
 */
export const MESSAGE_HISTORY_PAGE_SIZE = 200;
